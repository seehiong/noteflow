//src/components/AIAssistant.tsx

import React, { useState, useEffect } from 'react';
import { Sparkles, Key, Plus, Check } from 'lucide-react';

interface AIAssistantProps {
  code: string;
  onCodeChange: (newCode: string) => void;
  addConsoleLog: (type: 'system' | 'input-on' | 'input-off' | 'error', message: string) => void;
}

export const AIAssistant: React.FC<AIAssistantProps> = ({
  code,
  onCodeChange,
  addConsoleLog,
}) => {
  const [apiKey, setApiKey] = useState('');
  const [customPrompt, setCustomPrompt] = useState('');
  const [loading, setLoading] = useState(false);
  const [generatedCode, setGeneratedCode] = useState('');
  const [errorMsg, setErrorMsg] = useState('');
  const [selectedModel, setSelectedModel] = useState('gemini-2.5-flash');

  // Load saved API key from localStorage
  useEffect(() => {
    const savedKey = localStorage.getItem('gemini_api_key');
    if (savedKey) {
      setApiKey(savedKey);
    }
  }, []);

  const handleApiKeyChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const val = e.target.value.trim();
    setApiKey(val);
    localStorage.setItem('gemini_api_key', val);
  };

  const handleGenerate = async (promptText: string) => {
    if (!apiKey) {
      setErrorMsg('Please enter a Gemini API Key to continue.');
      return;
    }
    setErrorMsg('');
    setLoading(true);
    setGeneratedCode('');
    addConsoleLog('system', 'Initiating AI generation request...');

    const systemPrompt = `You are an AI Music Composer assisting in the NoteFlow MIDI IDE.
Your task is to generate or edit music written in the NoteFlow Notation (NFN) language.

--- NFN Syntax Guidelines ---
1. Notes format: PitchOctave/Duration (e.g. C4/1.0, D#4/0.5, Bb3/2.0, rest/1.5)
2. Multi-track format: Each line must start with a Track ID (e.g. T1, T2) and parameters, followed by space-separated note tokens.
3. Parameters:
   - For acoustic instruments: instrument=piano, instrument=organ, instrument=flute, instrument=cello, instrument=violin.
   - For synthesizer waveforms: synth=sine, synth=triangle, synth=square, synth=sawtooth, synth=drum.
   - To mute/toggle a track: track=on or track=off (default is track=on).
4. Example NFN Code:
   T1 instrument=piano track=on E4/1 E4/1 F4/1 G4/1
   T2 synth=sawtooth track=on C3/2 E3/2 F3/2
   T3 synth=drum track=on BD/1 HH/0.5 SD/0.5 HH/0.5

--- Strict Constraints ---
- Return ONLY the raw NFN code.
- Do NOT wrap in markdown code blocks like \`\`\`noteflow or \`\`\`txt.
- Do NOT write any conversational text, explanations, or labels before or after the code.
- Keep note values aligned in beats across parallel tracks.`;

    try {
      const response = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${selectedModel}:generateContent?key=${apiKey}`,
        {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({
            contents: [
              {
                parts: [
                  {
                    text: `${systemPrompt}\n\nCurrent NFN Code:\n${code}\n\nUser Instruction: ${promptText}`
                  }
                ]
              }
            ]
          }),
        }
      );

      if (!response.ok) {
        throw new Error(`API Request failed with status code ${response.status}`);
      }

      const data = await response.json();
      let resultText = data.candidates?.[0]?.content?.parts?.[0]?.text || '';

      // Clean up markdown wrapper leftovers if generated by the AI
      resultText = resultText
        .replace(/```[a-zA-Z]*\n/g, '')
        .replace(/```/g, '')
        .trim();

      if (!resultText) {
        throw new Error('Received an empty response from the AI model.');
      }

      setGeneratedCode(resultText);
      addConsoleLog('system', 'AI generation completed successfully.');
    } catch (err: any) {
      setErrorMsg(err.message || 'Generation failed.');
      addConsoleLog('error', `AI Generation Error: ${err.message}`);
    } finally {
      setLoading(false);
    }
  };

  const applyCodeReplacement = () => {
    if (generatedCode) {
      onCodeChange(generatedCode);
      setGeneratedCode('');
    }
  };

  const applyCodeAppend = () => {
    if (generatedCode) {
      onCodeChange(code + '\n' + generatedCode);
      setGeneratedCode('');
    }
  };

  const presets = [
    {
      label: '🎼 Accompaniment (T2)',
      prompt: 'Add a cello or organ backing accompaniment track as T2 to match the melody in T1.'
    },
    {
      label: '✨ Complete Song',
      prompt: 'Complete the rest of this song based on the current melody pattern.'
    },
    {
      label: '🥁 Add Drums (T3)',
      prompt: 'Add a backing drum kit track as T3 synth=drum with C2/BD, D2/SD, F#2/HH beats.'
    },
    {
      label: '🌉 Add Bridge',
      prompt: 'Add a contrasting bridge section that transitions back to the main theme.'
    }
  ];

  return (
    <div className="flex-1 flex flex-col p-3 font-sans text-xs text-slate-300 space-y-3.5 overflow-y-auto">
      {/* API Key Input */}
      <div className="flex flex-col gap-1">
        <div className="flex justify-between items-center">
          <label className="text-[10px] font-mono uppercase text-slate-400 flex items-center gap-1">
            <Key className="w-3.5 h-3.5 text-purple-400" />
            Gemini API Key
          </label>
          <a
            href="https://aistudio.google.com/"
            target="_blank"
            rel="noopener noreferrer"
            className="text-[9px] text-purple-400 hover:text-purple-300 underline font-mono"
          >
            Get Free Key
          </a>
        </div>
        <input
          type="password"
          value={apiKey}
          onChange={handleApiKeyChange}
          placeholder="Paste AI Studio API Key..."
          className="w-full bg-slate-950 border border-slate-800 rounded-lg px-2.5 py-1.5 text-xs text-slate-200 outline-none focus:border-purple-500/50"
        />
        {/* Model Selector Dropdown */}
        <div className="flex flex-col gap-1 mt-1">
          <select
            value={selectedModel}
            onChange={(e) => setSelectedModel(e.target.value)}
            className="w-full bg-slate-950 border border-slate-800 rounded-lg px-2 py-1 text-xs text-slate-200 outline-none transition-colors focus:border-purple-500/50"
          >
            <option value="gemini-2.5-flash">Gemini 2.5 Flash</option>
            <option value="gemini-3.1-flash-lite">Gemini 3.1 Flash Lite</option>
          </select>
        </div>
      </div>

      {/* Preset Prompts (Boilerplates) */}
      <div className="space-y-1">
        <span className="text-[9px] font-mono uppercase text-slate-400">Quick Presets</span>
        <div className="grid grid-cols-2 gap-2">
          {presets.map((preset, idx) => (
            <button
              key={idx}
              disabled={loading}
              onClick={() => handleGenerate(preset.prompt)}
              className="flex items-center justify-between px-2.5 py-1.5 bg-slate-900 border border-slate-800 rounded-lg hover:bg-slate-800 hover:border-slate-700 text-left transition-all hover:text-white disabled:opacity-50"
            >
              <span className="truncate">{preset.label}</span>
              <Sparkles className="w-3 h-3 text-purple-400 flex-shrink-0" />
            </button>
          ))}
        </div>
      </div>

      {/* Custom Prompt */}
      <div className="flex flex-col gap-1">
        <span className="text-[9px] font-mono uppercase text-slate-400">Custom Instruction</span>
        <div className="flex gap-2">
          <input
            type="text"
            value={customPrompt}
            onChange={(e) => setCustomPrompt(e.target.value)}
            placeholder="e.g. Transpose all tracks up 2 semitones, make it swing..."
            className="flex-1 bg-slate-950 border border-slate-800 rounded-lg px-2.5 py-1.5 text-xs text-slate-200 outline-none focus:border-purple-500/50"
            onKeyDown={(e) => {
              if (e.key === 'Enter' && customPrompt) {
                handleGenerate(customPrompt);
              }
            }}
          />
          <button
            disabled={loading || !customPrompt}
            onClick={() => handleGenerate(customPrompt)}
            className="px-3 bg-purple-600 hover:bg-purple-500 text-white rounded-lg transition-colors flex items-center justify-center disabled:bg-slate-800 disabled:text-slate-500"
          >
            Run
          </button>
        </div>
      </div>

      {/* Error Message */}
      {errorMsg && (
        <div className="bg-red-950/40 border border-red-900/60 text-red-300 p-2 rounded-lg text-[10px] leading-relaxed">
          {errorMsg}
        </div>
      )}

      {/* Loader */}
      {loading && (
        <div className="flex items-center justify-center gap-2 py-4 text-purple-400 italic font-medium">
          <div className="w-4 h-4 border-2 border-purple-500 border-t-transparent rounded-full animate-spin"></div>
          AI is composing notes...
        </div>
      )}

      {/* Preview / Action Area */}
      {generatedCode && (
        <div className="bg-slate-950 border border-purple-900/40 rounded-xl p-3 flex flex-col gap-3">
          <div className="flex justify-between items-center">
            <span className="font-semibold text-purple-400 flex items-center gap-1 font-mono text-[10px]">
              <Sparkles className="w-3.5 h-3.5" />
              Generated Response
            </span>
            <button
              onClick={() => setGeneratedCode('')}
              className="text-[10px] text-slate-500 hover:text-slate-300 font-mono"
            >
              Clear Preview
            </button>
          </div>

          <pre className="max-h-24 overflow-y-auto bg-slate-900 border border-slate-800 p-2 rounded-lg text-[10px] font-mono text-slate-400 leading-normal whitespace-pre-wrap select-all">
            {generatedCode}
          </pre>

          <div className="flex gap-2">
            <button
              onClick={applyCodeReplacement}
              className="flex-1 flex items-center justify-center gap-1 bg-purple-600 hover:bg-purple-500 text-white py-1.5 rounded-lg font-semibold transition-colors shadow-md"
            >
              <Check className="w-3.5 h-3.5" />
              Replace Code
            </button>
            <button
              onClick={applyCodeAppend}
              className="flex-1 flex items-center justify-center gap-1 bg-slate-800 hover:bg-slate-700 text-slate-200 py-1.5 border border-slate-700 rounded-lg font-semibold transition-all"
            >
              <Plus className="w-3.5 h-3.5" />
              Append to End
            </button>
          </div>
        </div>
      )}
    </div>
  );
};
